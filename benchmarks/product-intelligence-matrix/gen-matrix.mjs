#!/usr/bin/env node
/**
 * Full-matrix generator (benchmark program M1, plan 2026-09-02).
 *
 *   node gen-matrix.mjs          # writes matrix-full.yaml next to this script
 *
 * Crosses the 15 §43 jobs (matrix.yaml, verbatim) with the 10 shape
 * prototypes (shapes.yaml) into 150 cells. Natural pairs (a job whose own
 * §43 cell is absorbed by the shape) keep user_job / object_type /
 * acceptance_seed verbatim; their information_shape is canonicalized to the
 * absorbing shape prototype (matrix.yaml remains the §43 verbatim record).
 *
 * Priority layering (§46 saturation method; disambiguation recorded in the
 * 2026-09-03 phase report):
 *   1 = diagonal band (10 shapes × 3 high-frequency jobs) ∪ §43 natural pairs
 *   2 = corpus-uncovered paradigm (weakly covered — expand next, §46)
 *   3 = corpus-covered paradigm (redundant coverage)
 */
import { readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { parse, stringify } from "yaml";

const matrixDir = import.meta.dirname;

export function generateMatrix(shapesDoc, matrixDoc, corpusDoc) {
  const highFrequency = shapesDoc.high_frequency_jobs;
  const corpusCovered = (verb, shape) =>
    corpusDoc.entries.some((entry) => {
      const conditions = entry.trigger_conditions ?? {};
      const shapeObjects = shape.trigger_conditions?.object_type ?? [];
      return (
        (conditions.task_type ?? []).includes(verb) &&
        (conditions.object_type ?? []).some((object) => shapeObjects.includes(object))
      );
    });
  const cells = [];
  matrixDoc.cells.forEach((job, jobIndex) => {
    shapesDoc.shapes.forEach((shape, shapeIndex) => {
      const natural = shape.exemplar_cells.includes(job.id);
      const band = highFrequency.includes(job.user_job.verb);
      cells.push({
        id: `cell-j${String(jobIndex + 1).padStart(2, "0")}-s${String(shapeIndex + 1).padStart(2, "0")}`,
        job_shape: `${job.user_job.verb} × ${shape.name}`,
        user_job: job.user_job,
        information_shape: shape.information_shape,
        object_type: natural ? job.object_type : shape.suggested_objects[0],
        acceptance_seed: natural ? job.acceptance_seed : `${job.user_job.success}；${shape.seed_clause}`,
        priority: band || natural ? 1 : corpusCovered(job.user_job.verb, shape) ? 3 : 2,
      });
    });
  });
  return { version: "0.1", cells };
}

const invokedDirectly = resolve(process.argv[1] ?? "") === resolve(import.meta.filename);
if (invokedDirectly) {
  const read = (file) => readFile(join(matrixDir, file), "utf8").then(parse);
  const [shapes, matrix, corpus] = await Promise.all([
    read("shapes.yaml"),
    read("matrix.yaml"),
    readFile(join(matrixDir, "..", "..", "packages", "prax-knowledge", "data", "corpus-2026-09.yaml"), "utf8").then(parse),
  ]);
  const full = generateMatrix(shapes, matrix, corpus);
  const header = `# Generated by gen-matrix.mjs — DO NOT EDIT; regenerate instead.
# 15 §43 jobs (matrix.yaml) × 10 shape prototypes (shapes.yaml) = 150 cells.
# Natural pairs keep job/object/acceptance verbatim from matrix.yaml; their
# information_shape is canonicalized to the absorbing shape prototype.
# priority 1 = diagonal band (10 shapes × {decide, locate, explore}) ∪ §43
#   natural pairs; 2 = corpus-uncovered paradigm (expand next, §46); 3 =
#   corpus-covered (redundant). Corpus evidence: corpus-2026-09.yaml.
`;
  await writeFile(join(matrixDir, "matrix-full.yaml"), `${header}${stringify(full)}`);
  const byPriority = full.cells.reduce((counts, cell) => ({ ...counts, [cell.priority]: (counts[cell.priority] ?? 0) + 1 }), {});
  const band = full.cells.filter((cell) => shapes.high_frequency_jobs.includes(cell.user_job.verb)).length;
  console.log(`matrix-full.yaml: ${full.cells.length} cells; priority ${JSON.stringify(byPriority)}; band ${band}`);
}
